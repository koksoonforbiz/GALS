/**
 * Seed: LOCAL fixture for the puzzles browser test (e2e/puzzles.e2e.spec.ts).
 *
 * OPT-IN ONLY — never runs at boot, in migrations or in tests. Creates
 *   - a teacher  efa-teacher@gals.test
 *   - a student  efa-student@gals.test  (loginId: efa-student)
 *   - a published course "Puzzles e2e course" with one module and the T0
 *     questionnaire + puzzles gates before it, the student enrolled
 * with freshly generated passwords written to apps/api/.env.efa-e2e.local
 * (git-ignored by the root `.env.*.local` rule). The EF battery must be
 * seeded first (pnpm run seed:ef-battery).
 *
 *   pnpm run seed:efa-e2e-local [-- --reset]
 *
 * --reset  deletes the student's assessment occasions, gate completions and
 *          allocation claim, so the browser test can run again from the start.
 *
 * Refuses to run when NODE_ENV=production.
 */
import { PrismaClient } from '@prisma/client';
import { randomBytes } from 'crypto';
import * as bcrypt from 'bcryptjs';
import * as fs from 'fs';
import * as path from 'path';

if (process.env.NODE_ENV === 'production') {
  console.error('seed-efa-e2e-local refuses to run with NODE_ENV=production');
  process.exit(1);
}

const prisma = new PrismaClient();
const OUT = path.resolve(__dirname, '../../.env.efa-e2e.local');
const COURSE_TITLE = 'Puzzles e2e course';
const password = () => `Pz${randomBytes(9).toString('base64url')}7!`;

async function user(
  email: string,
  name: string,
  role: 'teacher' | 'student',
  pw: string,
  loginId?: string,
) {
  const data = {
    passwordHash: await bcrypt.hash(pw, 10),
    name,
    role,
    isActive: true,
    isTemporaryPassword: false,
    termsAcceptedAt: new Date(),
    passwordChangedAt: new Date(),
    ...(loginId ? { loginId } : {}),
  };
  return prisma.user.upsert({ where: { email }, create: { email, ...data }, update: data });
}

async function main() {
  const reset = process.argv.includes('--reset');
  const set = await prisma.efaStimulusSet.findFirst({ where: { batteryVersion: '2.0' } });
  if (!set) throw new Error('Seed the EF battery first: pnpm run seed:ef-battery');

  const tpw = password();
  const spw = password();
  const teacher = await user('efa-teacher@gals.test', 'Puzzles Teacher', 'teacher', tpw);
  const student = await user(
    'efa-student@gals.test',
    'Puzzles Student',
    'student',
    spw,
    'efa-student',
  );

  let course = await prisma.course.findFirst({
    where: { teacherId: teacher.id, title: COURSE_TITLE },
  });
  if (!course) {
    course = await prisma.course.create({
      data: {
        title: COURSE_TITLE,
        description: 'Local browser-test fixture for the attention and memory puzzles.',
        teacherId: teacher.id,
        status: 'PUBLISHED',
        visibility: 'PUBLIC',
      },
    });
  }
  let mod = await prisma.courseModule.findFirst({ where: { courseId: course.id, orderIndex: 0 } });
  if (!mod) {
    mod = await prisma.courseModule.create({
      data: { courseId: course.id, title: 'Session 1', orderIndex: 0 },
    });
    await prisma.moduleItem.create({
      data: {
        moduleId: mod.id,
        type: 'PAGE',
        title: 'Welcome',
        orderIndex: 0,
        contentMdx: '# Welcome\n\nSession 1 content.',
      },
    });
  }
  for (const [kind, sequence] of [
    ['EF_QUESTIONNAIRE', 10],
    ['EF_TESTS', 20],
  ] as const) {
    await prisma.courseGate.upsert({
      where: { courseId_kind_occasion: { courseId: course.id, kind, occasion: 'T0' } },
      create: {
        courseId: course.id,
        kind,
        occasion: 'T0',
        position: 'BEFORE_MODULE',
        moduleId: mod.id,
        sequence,
      },
      update: { moduleId: mod.id, sequence },
    });
  }
  await prisma.enrollment.upsert({
    where: { studentId_courseId: { studentId: student.id, courseId: course.id } },
    create: { studentId: student.id, courseId: course.id, status: 'ACTIVE' },
    update: { status: 'ACTIVE' },
  });

  if (reset) {
    await prisma.efaOccasion.deleteMany({ where: { studentId: student.id, courseId: course.id } });
    await prisma.studentGateCompletion.deleteMany({ where: { studentId: student.id } });
    await prisma.efaAllocationSlot.updateMany({
      where: { claimedStudentId: student.id },
      data: { claimedAt: null, claimedStudentId: null, claimedCourseId: null },
    });
  }

  fs.writeFileSync(
    OUT,
    [
      '# Generated by seed-efa-e2e-local.ts — local only, never commit.',
      `E2E_COURSE_ID=${course.id}`,
      `E2E_STUDENT_LOGIN=efa-student`,
      `E2E_STUDENT_PASSWORD=${spw}`,
      `E2E_TEACHER_EMAIL=efa-teacher@gals.test`,
      `E2E_TEACHER_PASSWORD=${tpw}`,
      '',
    ].join('\n'),
  );
  console.log(
    `Fixture ready: course ${course.id}${reset ? ' (student state reset)' : ''}. Credentials in ${OUT}`,
  );
}

main()
  .catch((e) => {
    console.error((e as Error).message);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
