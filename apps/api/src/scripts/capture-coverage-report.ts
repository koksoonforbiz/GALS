/**
 * Observed-vs-expected capture coverage (Prompt B, P8 / B10): after the
 * scripted-learner browser runs, which catalogue actions appeared, whether
 * their payloads pass the catalogue schema, and how complete the streams
 * and sessions are. Writes docs/process-mining/audit/CAPTURE_COVERAGE_RESULT.md.
 *
 *   pnpm --filter @ats/api exec ts-node --transpile-only src/scripts/capture-coverage-report.ts \
 *     --since 2026-11-25T16:41:10Z [--out ../../docs/process-mining/audit/CAPTURE_COVERAGE_RESULT.md]
 *
 * Reads the database in DATABASE_URL (local stack). Read-only.
 */
import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { PrismaClient } from '@prisma/client';
import { ACTION_CATALOGUE, checkMetadata, type ActionSpec } from '@ats/shared';

const catalogue = ACTION_CATALOGUE as Record<string, ActionSpec>;

/** Why a live action can be absent from a scripted run (known, not a capture gap). */
const NOT_EXERCISED: Array<[RegExp, string]> = [
  [/^DIALOGUE_|^STUDY_GUIDE|^STUDIO_OUTPUT/, 'Mode B (not in this study)'],
  [
    /^CHATBOT_MESSAGE_RECEIVED$|^FEEDBACK_RECEIVED$|^QUESTION_GRADED$|^STEP_/,
    'needs a live LLM provider (none locally)',
  ],
  [/^WEBGAZER_|^PUPIL_|^PYFEAT_|^RECORDING_/, 'needs a real camera / eye tracker'],
  [/^ASSESSMENT_|^ATTEMPT_SUBMITTED$/, 'legacy assessments (not in the course)'],
  [
    /^PRACTICE_|^CARD_|^REVIEW_QUEUE|^SPACED_REP|^INTERVENTION_|^STRATEGY_|^QUESTION_/,
    'Mode A strategies (need an LLM to generate)',
  ],
  [
    /^PROGRESS_CHECKED$|^RESUME_ANSWERED$|^ANSWER_CONFIDENCE_RATED$|^INTENTION_TAGGED$/,
    'learner prompt not answered in the scripted runs (shown only after 10 min / 5 min away / in practice tests / chosen)',
  ],
  [/^ANNOUNCEMENT_/, 'no announcement was active during the runs'],
  [/^CODE_/, 'code practice (not in the course)'],
  [/^EF_|^GATE_|^KNOWLEDGE_TEST_SUBMITTED|^KNOWLEDGE_TEST_GATE/, 'server-written'],
];

function reasonFor(action: string): string {
  for (const [re, why] of NOT_EXERCISED) if (re.test(action)) return why;
  return 'not exercised by the scripted runs';
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

async function main() {
  const since = new Date(arg('--since') ?? Date.now() - 6 * 3600_000);
  const out = resolve(
    arg('--out') ??
      resolve(__dirname, '../../../../docs/process-mining/audit/CAPTURE_COVERAGE_RESULT.md'),
  );
  const prisma = new PrismaClient();
  try {
    const sessions = await prisma.studentSession.findMany({
      where: { startedAt: { gte: since } },
      select: { id: true, userId: true, endedAt: true, closeReason: true },
    });
    const ids = sessions.map((s) => s.id);
    const rows = await prisma.activityLog.findMany({
      where: { sessionId: { in: ids } },
      select: { action: true, metadata: true, clientEventId: true, tabId: true },
    });
    const byAction = new Map<string, { n: number; invalid: number; issues: Map<string, number> }>();
    for (const r of rows) {
      const a = String(r.action);
      const b = byAction.get(a) ?? { n: 0, invalid: 0, issues: new Map() };
      b.n++;
      const errs = checkMetadata(a, r.metadata) ?? ['(not in catalogue)'];
      if (errs.length) {
        b.invalid++;
        for (const e of errs) b.issues.set(e, (b.issues.get(e) ?? 0) + 1);
      }
      byAction.set(a, b);
    }
    const client = rows.filter((r) => r.clientEventId).length;
    const streams: Record<string, number> = {};
    for (const t of [
      'click_logs',
      'cursor_logs',
      'scroll_logs',
      'keystroke_logs',
      'visibility_logs',
      'clipboard_logs',
    ]) {
      const [c] = await prisma.$queryRawUnsafe<Array<{ n: bigint }>>(
        `SELECT count(*)::bigint AS n FROM "${t}" WHERE "sessionId" = ANY($1::text[])`,
        ids,
      );
      streams[t] = Number(c?.n ?? 0);
    }
    const gaps = await prisma.captureQuality.aggregate({
      where: { sessionId: { in: ids }, kind: 'gap' },
      _sum: { count: true },
      _count: { _all: true },
    });
    const issues = await prisma.ingestIssue.groupBy({
      by: ['kind'],
      where: { sessionId: { in: ids } },
      _sum: { eventCount: true },
    });
    const parsed = await prisma.sessionParseRun.findMany({
      where: { sessionId: { in: ids }, status: 'ok' },
      select: { sessionId: true },
      distinct: ['sessionId'],
    });

    const live = Object.entries(catalogue).filter(([, s]) => !s.deprecated);
    const lines: string[] = [];
    lines.push('# Capture coverage result (Prompt B, phase 8)');
    lines.push('');
    lines.push(
      `_Generated by \`apps/api/src/scripts/capture-coverage-report.ts\` on ${new Date().toISOString()} from the scripted-learner browser runs since ${since.toISOString()} on the local stack._`,
    );
    lines.push('');
    lines.push('## Runs');
    lines.push('');
    lines.push(
      'Playwright suites: interactive lesson (Session 1, every slide type and gate, Prompt Lab), EF puzzles (one full T0 occasion), knowledge test, study notes, camera guard, capture resilience (offline, reload, exactly once, no gaps), learner prompts (goal card, reflection).',
    );
    lines.push('');
    lines.push(
      `- Sessions: ${sessions.length} (learners: ${new Set(sessions.map((s) => s.userId)).size}), closed: ${sessions.filter((s) => s.endedAt).length}, parsed: ${parsed.length}`,
    );
    lines.push(
      `- Activity rows: ${rows.length} (${client} sent by the browser with a client event id)`,
    );
    lines.push(
      `- Stream rows: ${Object.entries(streams)
        .map(([k, v]) => `${k} ${v}`)
        .join(', ')}`,
    );
    lines.push(`- Sequence gaps: ${gaps._count._all} (${gaps._sum.count ?? 0} missing events)`);
    lines.push(
      `- Ingest issues: ${issues.length ? issues.map((i) => `${i.kind} ${i._sum.eventCount ?? 0}`).join(', ') : 'none'}`,
    );
    const observed = live.filter(([a]) => byAction.has(a));
    const valid = observed.filter(([a]) => byAction.get(a)!.invalid === 0);
    lines.push(
      `- Catalogue actions observed: ${observed.length} of ${live.length} live actions; ${valid.length} with every row schema-valid`,
    );
    lines.push('');
    lines.push(
      'Legend: ✅ observed, every row passes its catalogue schema · ⚠️ observed, some rows fail · ❌ not observed (reason given).',
    );
    lines.push('');
    lines.push('| Action | Surface | Rows | Schema | Status / reason |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const [a, s] of live.sort(
      (x, y) => x[1].surface.localeCompare(y[1].surface) || x[0].localeCompare(y[0]),
    )) {
      const b = byAction.get(a);
      if (!b) {
        lines.push(`| \`${a}\` | ${s.surface} | 0 |  | ❌ ${reasonFor(a)} |`);
        continue;
      }
      const ok = b.invalid === 0;
      const top = [...b.issues]
        .sort((x, y) => y[1] - x[1])
        .slice(0, 2)
        .map(([k, n]) => `${k} (${n})`)
        .join('; ');
      lines.push(
        `| \`${a}\` | ${s.surface} | ${b.n} | ${ok ? 'valid' : `${b.invalid} invalid: ${top}`} | ${ok ? '✅' : '⚠️'} |`,
      );
    }
    lines.push('');
    writeFileSync(out, lines.join('\n'));
    console.log(`wrote ${out}: ${observed.length}/${live.length} observed, ${valid.length} valid`);
  } finally {
    await prisma.$disconnect();
  }
}

main().then(
  () => process.exit(0),
  (err) => {
    console.error(err);
    process.exit(1);
  },
);
