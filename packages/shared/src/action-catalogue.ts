const ZOD: Record<MetaType, z.ZodTypeAny> = {
  string: z.string(),
  number: z.number(),
  boolean: z.boolean(),
  object: z.record(z.unknown()),
  array: z.array(z.unknown()),
  any: z.unknown(),
};

/** The metadata schema of an action: required keys typed, optional keys typed when present, others allowed. */
export function metadataSchema(action: string): z.ZodTypeAny | null {
  const spec = (ACTION_CATALOGUE as Record<string, ActionSpec>)[action];
  if (!spec) return null;
  const shape: Record<string, z.ZodTypeAny> = {};
  for (const [k, t] of Object.entries(spec.required ?? {})) shape[k] = ZOD[t];
  for (const [k, t] of Object.entries(spec.optional ?? {})) shape[k] = ZOD[t].nullish();
  return z.object(shape).passthrough();
}

/** Missing or mistyped metadata for an action ([] when valid; null when the action is unknown). */
export function checkMetadata(action: string, metadata: unknown): string[] | null {
  const schema = metadataSchema(action);
  if (!schema) return null;
  const r = schema.safeParse(metadata ?? {});
  return r.success
    ? []
    : r.error.issues.map((i) => `${i.path.join('.') || '(metadata)'}:${i.code}`);
}
