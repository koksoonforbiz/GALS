/**
 * The action catalogue: one entry per ActivityAction (Prompt B, B1). It is
 * the source of truth for what the platform records:
 *   level     ACT (learner action) | SYS (system) | QUALITY (capture health)
 *             | REF (reference outcome)
 *   side      who writes it: the browser, the API, or both
 *   kind      instant, or interval (has a duration or a closing event)
 *   surface   where it happens (Prompt A coverage matrix)
 *   textFields free-text metadata keys (recorded: consent is on the study
 *             consent form; TEXT_CONSENT_IN_APP=true gates them again)
 *   required / optional  metadata keys and their JSON type. Seeded on
 *             2026-11-26 from the keys present in every / some stored row
 *             of the local database (observedN rows); edit by hand since.
 *   deprecated in the enum, no emitter (kept: enum values are never dropped)
 *
 * docs/process-mining/ACTION_CATALOGUE.md is generated from this file
 * (pnpm --filter @ats/shared run gen:catalogue). CI checks that code, the
 * Prisma enum and library.v2.json agree with it
 * (apps/api/src/learning-events/catalogue.spec.ts).
 */
